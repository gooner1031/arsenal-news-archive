ORDER = ['移籍・噂','公式発表','試合','インタビュー・コメント','戦術・分析','負傷・コンディション','裏話・エピソード','アカデミー・若手','代表','契約・クラブ運営','記録・データ','ネタ','SNS・選手の発信','ファン・スタジアム','リーグ・他クラブ','考察・意見']

def categorize(plain, extra=(), meta=None):
    head = plain[:HEAD]
    out = []
    meta = meta or {}
    for c, (strong, weak) in RULES.items():
        if strong.search(head):
            out.append(c); continue
        ws = {m.group(0) for m in weak.finditer(head)}
        if len(ws) >= 2: out.append(c)
    for c in extra:
        if c not in out: out.append(c)
    # fallbacks for posts that matched nothing
    if not out:
        L = len(head.strip())
        if meta.get('clubs') and not meta.get('arsenal') and not meta.get('people'): out.append('リーグ・他クラブ')
        elif L >= 140 and not meta.get('src') and not meta.get('ext'): out.append('考察・意見')
    return [c for c in ORDER if c in out]
