#!/usr/bin/env python3
"""WOWOW（CL）・DAZN（カラバオ杯・FA杯）公式ハイライトのタイトル判定の回帰テスト。実行: python3 tools/test_highlights.py"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from hl_jp import parse_jp, fits
from fetch_highlights_jp import entry, link
W = '【アーセナル vs ドルトムント】UEFAチャンピオンズリーグ 2026-27 リーグフェーズ MD5／3分ハイライト【WOWOW】'
D = '【イプスウィッチ×アーセナル ｜ハイライト】カラバオカップ 3回戦｜2026-27シーズン'
D2 = '【鎌田大地がビューティフルゴール＆冨安健洋が今季初フル出場｜クリスタル・パレス×ミドルズブラ ｜ハイライト】カラバオカップ 3回戦｜2026-27シーズン'
S1 = '【チェルシー×アーセナル｜ハイライト】カラバオカップ 準決勝 第1戦｜2025-26'
S2 = '【アーセナル×チェルシー｜ハイライト】カラバオカップ 準決勝 第2戦｜2025-26'
def M(o, c, ha): return {'o': o, 'c': c, 'ha': ha}
T = [
 (parse_jp(W) == ('wowow', 'アーセナル', 'ドルトムント', 'チャンピオンズリーグ', 2026), 'WOWOWのタイトルを読める'),
 (parse_jp(D) == ('dazn', 'イプスウィッチ', 'アーセナル', 'カラバオ杯', 2026), 'DAZNのタイトルを読める'),
 (parse_jp(D2) == ('dazn', 'クリスタル・パレス', 'ミドルズブラ', 'カラバオ杯', 2026), '見出しつきのDAZNタイトルを読める'),
 (parse_jp('【アーセナル×ベティス｜ハイライト】親善試合｜2026-27シーズン') is None, '対象外の大会は拾わない'),
 (parse_jp('【アーセナル vs ドルトムント】UEFAチャンピオンズリーグ 2026-27 MD5／試合前会見') is None, 'ハイライト以外は拾わない'),
 (fits(parse_jp(W), M('ドルトムント', 'チャンピオンズリーグ', 'H'), 2026), 'CLホーム戦に一致'),
 (not fits(parse_jp(W), M('ドルトムント', 'チャンピオンズリーグ', 'A'), 2026), 'ホーム／アウェイが逆なら不一致'),
 (not fits(parse_jp(W), M('ドルトムント', 'チャンピオンズリーグ', 'H'), 2025), 'シーズンが違えば不一致'),
 (not fits(parse_jp(W), M('バイエルン', 'チャンピオンズリーグ', 'H'), 2026), '相手が違えば不一致'),
 (fits(parse_jp(D), M('イプスウィッチ', 'カラバオ杯', 'A'), 2026), 'カラバオ杯アウェイ戦に一致'),
 (not fits(parse_jp(D2), M('クリスタル・パレス', 'カラバオ杯', 'H'), 2026), 'アーセナル以外の試合は不一致'),
 (fits(parse_jp(S1), M('チェルシー', 'カラバオ杯', 'A'), 2025) and not fits(parse_jp(S1), M('チェルシー', 'カラバオ杯', 'H'), 2025), '準決勝 第1戦と第2戦を取り違えない(1)'),
 (fits(parse_jp(S2), M('チェルシー', 'カラバオ杯', 'H'), 2025) and not fits(parse_jp(S2), M('チェルシー', 'カラバオ杯', 'A'), 2025), '準決勝 第1戦と第2戦を取り違えない(2)'),
 (fits(parse_jp('【パリ・サンジェルマン vs アーセナル】UEFAチャンピオンズリーグ 2025-26 決勝／3分ハイライト【WOWOW】'), M('PSG', 'チャンピオンズリーグ', 'N'), 2025), '中立地の決勝・クラブ名の別表記に一致'),
 (fits(parse_jp('【アーセナル×アストンヴィラ｜ハイライト】FAカップ 3回戦｜2026-27シーズン'), M('アストン・ヴィラ', 'FA杯', 'H'), 2026), 'FA杯・中黒なしの表記に一致'),
 (not fits(parse_jp(D), M('イプスウィッチ', 'プレミアリーグ', 'A'), 2026), 'プレミアリーグの試合には付けない'),
]
MS = {'2026-11-24': M('ドルトムント', 'チャンピオンズリーグ', 'H'), '2026-01-14': M('チェルシー', 'カラバオ杯', 'A'), '2026-02-03': M('チェルシー', 'カラバオ杯', 'H'),
      '2025-10-21': M('アトレティコ・マドリード', 'チャンピオンズリーグ', 'H'), '2026-05-05': M('アトレティコ・マドリード', 'チャンピオンズリーグ', 'H')}
BY = {'w': entry('w', W, 'wowow', '2026-11-25'), 's1': entry('s1', S1, 'dazn'), 's2': entry('s2', S2, 'dazn'),
      'at': entry('at', '【アーセナル vs アトレティコ】UEFAチャンピオンズリーグ 2025-26 準決勝 2nd leg／3分ハイライト【WOWOW】', 'wowow'),
      'at2': entry('at2', '【アーセナル vs アトレティコ】UEFAチャンピオンズリーグ 2025-26 準決勝 2nd leg／3分ハイライト【WOWOW】', 'wowow', '2026-05-06')}
n = link(BY, MS)
T += [
 (entry('x', D2, 'dazn') is None and entry('x', W, 'dazn') is None, 'アーセナル以外の試合・配信元ちがいは保存しない'),
 (BY['w'].get('d') == '2026-11-24', 'RSSの動画を試合日に結び付ける'),
 (BY['s1'].get('d') == '2026-01-14' and BY['s2'].get('d') == '2026-02-03', '第1戦・第2戦をそれぞれの試合日に結び付ける'),
 (BY['at2'].get('d') == '2026-05-05', '同じ相手とホームで2回当たっても、投稿日があれば正しい試合に付く'),
 ('d' not in BY['at'], '同じ相手とホームで2回当たり投稿日もないときは、決め打ちしない'),
]
bad = [n for ok, n in T if not ok]
print('NG  ' + '\nNG  '.join(bad) if bad else 'OK  ハイライトのタイトル判定 %d 件' % len(T))
sys.exit(1 if bad else 0)
